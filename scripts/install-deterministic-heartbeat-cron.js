#!/usr/bin/env bun
/** Provision the opt-in no-model Engram heartbeat script cron. */

import { parseArgs } from "node:util";
import { existsSync, realpathSync } from "node:fs";
import { resolve } from "node:path";
import { spawnSync } from "node:child_process";
import { loadEngramConfig } from "./config.js";

const { values: args } = parseArgs({
  options: {
    action: { type: "string" }, workspace: { type: "string" }, "agent-id": { type: "string" },
    session: { type: "string", default: "main" }, "label-prefix": { type: "string" },
    "cron-name": { type: "string" }, schedule: { type: "string" }, tz: { type: "string" },
    disabled: { type: "boolean", default: false }, "dry-run": { type: "boolean", default: false },
    help: { type: "boolean", short: "h", default: false },
  }, strict: true,
});

const action = args.action ?? "install";
const fail = (message) => { console.error(`❌ ${message}`); process.exit(2); };
const canonical = (path) => { const absolute = resolve(path); try { return realpathSync(absolute); } catch { return absolute; } };

function usage(exitCode = 0) {
  console.log(`install-deterministic-heartbeat-cron

Usage:
  bun skills/engram/scripts/install-deterministic-heartbeat-cron.js \\
    --workspace <agent-workspace> [--action install|status|uninstall] [options]

Creates payload.kind=script, not agentTurn. OpenClaw requires
cron.triggers.enabled=true before script payloads may run. Start with
--disabled for a canary, then enable only after that gateway preflight passes.
`);
  process.exit(exitCode);
}

if (args.help) usage();
if (!["install", "status", "uninstall"].includes(action)) fail(`Unknown action: ${action}`);
if (!args.workspace) fail("--workspace is required");
const workspace = canonical(args.workspace);
if (!existsSync(resolve(workspace, "engram.json"))) fail(`Workspace does not contain engram.json: ${workspace}`);
const config = loadEngramConfig(workspace);
const agentId = String(args["agent-id"] || config.agent || "main").replace(/^agent-/, "");
const session = args.session;
const labelPrefix = args["label-prefix"] || (agentId === "main" ? "hb" : `${agentId}-hb`);
const declared = config?.cron?.expectedSchedule;
const schedule = args.schedule || (declared?.kind === "cron" ? declared.expr : undefined);
if (!schedule) fail("--schedule is required when engram.json has no cron.expectedSchedule declaration");
const tz = args.tz || (declared?.kind === "cron" ? declared.tz : undefined) || "UTC";
const cronName = args["cron-name"] || `Heartbeat (Engram deterministic) — ${agentId}`;
const js = (value) => JSON.stringify(value);

/** Source executes in OpenClaw Code Mode: no imports, filesystem, or network. */
function buildScript() {
  const runnerCommand = [
    "bun ./skills/engram/scripts/heartbeat-runner.js", `--workspace ${js(workspace)}`,
    `--agent-id ${js(agentId)}`, `--session ${js(session)}`, `--label-prefix ${js(labelPrefix)}`,
    "--all-active-sessions --timeout-ms 300000",
    "--spawn-hb-domains-write",
  ].join(" ");
  const claimCommand = `bun ./skills/engram/scripts/spawn-claim.js --workspace ${js(workspace)} --agent-id ${js(agentId)}`;
  return `// Generated by install-deterministic-heartbeat-cron.js.
const WORKSPACE = ${js(workspace)};
const AGENT_ID = ${js(agentId)};
const execText = async (command, yieldMs) => {
  const value = await tools.callValue("exec", { command, workdir: WORKSPACE, yieldMs, timeout: 420 });
  return String(value?.aggregated ?? value?.stdout ?? value?.output ?? "");
};
const parseClaim = (text) => text.split(/\\r?\\n/).flatMap((line) => {
  try { const entry = JSON.parse(line); return entry?.action === "spawn" ? [entry] : []; } catch { return []; }
});
const dispatch = async (text) => {
  const records = parseClaim(text); let spawned = 0; const errors = [];
  for (const record of records) {
    try {
      const result = await tools.callValue("sessions_spawn", { task: record.task, label: record.runtimeLabel || record.label, model: record.model, cleanup: "delete", cwd: WORKSPACE });
      const dispatchRef = encodeURIComponent(String(result?.sessionKey ?? result?.sessionId ?? result?.id ?? record.runId));
      await execText("bun ./skills/engram/scripts/spawn-ack.js --workspace " + JSON.stringify(WORKSPACE) + " --run-id " + record.runId + " --accepted true --dispatch-ref-uri " + dispatchRef + " --json", 60000);
      spawned += 1;
    } catch (error) {
      errors.push(String(error));
      const dispatchRef = encodeURIComponent("dispatch-error:" + String(error).slice(0, 500));
      try { await execText("bun ./skills/engram/scripts/spawn-ack.js --workspace " + JSON.stringify(WORKSPACE) + " --run-id " + record.runId + " --accepted false --dispatch-ref-uri " + dispatchRef + " --json", 60000); } catch {}
    }
  }
  return { claimed: records.length, spawned, errors };
};
const stale = await dispatch(await execText(${js(claimCommand)}, 60000));
const runnerText = await execText(${js(runnerCommand)}, 120000);
const current = await dispatch(await execText(${js(claimCommand)}, 60000));
let runner = null; try { runner = JSON.parse(runnerText.trim()); } catch {}
return { state: { lastRunAt: new Date().toISOString(), staleClaimed: stale.claimed, currentClaimed: current.claimed, spawned: stale.spawned + current.spawned, errors: [...stale.errors, ...current.errors].slice(0, 5) } };`;
}

function buildSpec() {
  return {
    name: cronName,
    description: "Deterministic no-model Engram heartbeat. Managed by install-deterministic-heartbeat-cron.js.",
    agentId, schedule: { kind: "cron", expr: schedule, tz, staggerMs: 0 },
    sessionTarget: "isolated", sessionKey: `agent:${agentId}:${session}`, wakeMode: "now",
    payload: {
      kind: "script", source: buildScript(), timeoutSeconds: 420, toolBudget: 20,
      toolsAllow: ["exec", "sessions_spawn"],
    },
    delivery: { mode: "none" }, enabled: !args.disabled,
  };
}

function openclaw(argv, input) {
  const binary = process.env.ENGRAM_OPENCLAW || Bun.which("openclaw");
  if (!binary) fail("openclaw binary not found on PATH");
  // Test and development overrides may point directly at a JS file. Execute
  // those through the current runtime: Unix shebang execution is not portable
  // to Windows.
  const isJavaScript = /\.(?:c|m)?js$/i.test(binary);
  const result = spawnSync(isJavaScript ? process.execPath : binary,
    isJavaScript ? [binary, ...argv] : argv,
    { encoding: "utf8", input, shell: false });
  if (result.error || result.status !== 0) { console.error(result.stderr || result.error?.message || `openclaw exited ${result.status}`); process.exit(1); }
  return result.stdout || "";
}
function parseJson(output) { const start = output.indexOf("{"); if (start < 0) throw new Error("OpenClaw returned no JSON"); return JSON.parse(output.slice(start)); }
function existingJob() { return (parseJson(openclaw(["cron", "list", "--all", "--json"]))?.jobs || []).find((job) => job.name === cronName) ?? null; }

function install() {
  const spec = buildSpec();
  if (args["dry-run"]) return console.log(JSON.stringify(spec, null, 2));
  const existing = existingJob();
  const base = existing ? ["cron", "edit", existing.id] : ["cron", "add", "--json"];
  const command = [
    ...base, "--name", spec.name, "--description", spec.description, "--agent", spec.agentId,
    "--session", "isolated", "--session-key", spec.sessionKey, "--wake", spec.wakeMode,
    "--cron", spec.schedule.expr, "--tz", spec.schedule.tz, "--exact", "--tools", spec.payload.toolsAllow.join(","),
    "--no-deliver", "--script", "-", "--script-timeout-seconds", String(spec.payload.timeoutSeconds),
    "--script-tool-budget", String(spec.payload.toolBudget),
  ];
  if (existing) command.push(args.disabled ? "--disable" : "--enable");
  else if (args.disabled) command.push("--disabled");
  const output = openclaw(command, spec.payload.source);
  const id = existing?.id ?? parseJson(output).id ?? "<unknown>";
  console.log(`✅ ${existing ? "updated" : "created"} deterministic heartbeat cron ${id}`);
}
function status() { const job = existingJob(); console.log(job ? JSON.stringify(job, null, 2) : "no deterministic heartbeat cron found"); }
function uninstall() { if (args["dry-run"]) return; const job = existingJob(); if (!job) return console.log("no deterministic heartbeat cron found"); openclaw(["cron", "rm", job.id]); console.log(`✅ removed deterministic heartbeat cron ${job.id}`); }
if (action === "install") install();
if (action === "status") status();
if (action === "uninstall") uninstall();
export { buildScript, buildSpec };
